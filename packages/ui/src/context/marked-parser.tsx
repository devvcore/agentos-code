import katex from "katex"
import { Marked, type MarkedExtension, type Tokens } from "marked"
import markedShiki from "marked-shiki"

export function createMarkdownParser(highlight: (code: string, language: string) => string | Promise<string>) {
  return new Marked(
    {
      renderer: {
        link({ href, title, text }) {
          const titleAttr = title ? ` title="${title}"` : ""
          return `<a href="${href}"${titleAttr} class="external-link" target="_blank" rel="noopener noreferrer">${text}</a>`
        },
        // Local images cannot load from the app origin; the renderer resolves `data-markdown-src`
        // through the host app. Remote images keep the default rendering.
        image({ href, title, text }) {
          if (/^(https?:|data:|blob:)/i.test(href.trim())) return false
          const titleAttr = title ? ` title="${escapeHtml(title)}"` : ""
          return `<img data-markdown-src="${escapeHtml(href)}" alt="${escapeHtml(text)}"${titleAttr}>`
        },
      },
    },
    katexExtension,
    markedShiki({
      // ```chart blocks hold a JSON chart spec; the renderer mounts an interactive chart in place of the source.
      highlight: (code, language) => (language === "chart" ? chartHtml(code) : highlight(code, language)),
    }),
  )
}

export function chartHtml(source: string) {
  return `<div data-component="markdown-chart"><div data-slot="markdown-chart-source" hidden>${escapeHtml(source)}</div></div>`
}

function escapeHtml(text: string) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;")
}

const inlineMathRegex = /^\\\(((?:\\.|[^\\\n])*?)\\\)/
const blockMathRegex = /^\$\$\n([\s\S]+?)\n\$\$(?:\n|$)/

const katexExtension: MarkedExtension = {
  extensions: [
    {
      name: "inlineKatex",
      level: "inline",
      start(src) {
        const index = src.indexOf("\\(")
        if (index === -1) return
        return index
      },
      tokenizer(src) {
        const match = src.match(inlineMathRegex)
        if (!match) return
        return {
          type: "inlineKatex",
          raw: match[0],
          text: match[1].trim(),
          displayMode: false,
        }
      },
      renderer: renderKatexToken,
    },
    {
      name: "blockKatex",
      level: "block",
      tokenizer(src) {
        const match = src.match(blockMathRegex)
        if (!match) return
        return {
          type: "blockKatex",
          raw: match[0],
          text: match[1].trim(),
          displayMode: true,
        }
      },
      renderer: renderKatexToken,
    },
  ],
}

function renderKatexToken(token: Tokens.Generic) {
  return katex.renderToString(typeof token.text === "string" ? token.text : "", {
    displayMode: token.displayMode === true,
    throwOnError: false,
  })
}
